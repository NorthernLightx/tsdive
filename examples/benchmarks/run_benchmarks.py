"""Deterministic benchmark runner over the synthetic backbone.

    uv run python examples/benchmarks/run_benchmarks.py            # verify
    uv run python examples/benchmarks/run_benchmarks.py --update   # regenerate

Every number derives from seeded synthetic data (seed=42). Counts and
fixed-decimal values only - no wall-clock, no platform strings - so the
committed BENCHMARKS.md compares byte-for-byte in CI. All rows are
labelled SYNTHETIC; real TEP/3W numbers stay gated (docs/DATA.md).
"""

from __future__ import annotations

import argparse
import sys
import tempfile
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).parents[2]
BENCH_MD = ROOT / "BENCHMARKS.md"

HEADER = """# Benchmarks

Every row of the table below is computed from the SYNTHETIC validation
backbone (seed=42, 4 loops, 48 h @ 60 s; four fault archetypes, one per
loop, injected during day 2). Real-data sections come after the table -
there are three, one per study - are written by their own study runner,
and are carried through this generator untouched: everything from the
first `## REAL` heading onward is preserved verbatim. See docs/DATA.md.

Regenerated by `make bench`; CI compares this file byte-for-byte.
"""

# The split point, not a section delimiter: everything from the FIRST
# `## REAL` heading to the end of the file is real-data material, however
# many sections it contains, and is preserved verbatim on regeneration.
# The synthetic table above it is the only part this script computes.
APPENDED_MARKER = "\n## REAL"

DAY1 = (
    pd.Timestamp("2025-01-01 00:00:00+00:00"),
    pd.Timestamp("2025-01-02 00:00:00+00:00"),
)
DAY2 = (
    pd.Timestamp("2025-01-02 00:00:00+00:00"),
    pd.Timestamp("2025-01-03 00:00:00+00:00"),
)


def _contract(stepped: bool = True):
    from tsdive.store.sampling_contract import CalculationBasis, RetrievalMode, SamplingContract

    return SamplingContract(
        CalculationBasis.TIME_WEIGHTED, RetrievalMode.RECORDED, stepped=stepped
    )


def _window_features(store, ident) -> dict:
    """One honest feature dict per half-day window for one tag."""
    import numpy as np

    out = []
    for lo, hi in (DAY1, DAY2):
        w = store.read_window(ident, lo.to_pydatetime(), hi.to_pydatetime(), _contract())
        good = w.frame[w.frame["valid"]]
        vals = good["value"].astype(float)
        arr = vals.to_numpy(dtype=float)
        med = float(np.median(arr))
        changes = int((vals.diff().fillna(0.0) != 0).sum())
        span_h = (hi - lo).total_seconds() / 3600.0
        out.append(
            {
                "weighted_mean": round(float(vals.mean()), 4),
                "std": round(float(vals.std()), 4),
                "min": round(float(vals.min()), 4),
                "max": round(float(vals.max()), 4),
                "median": round(med, 4),
                "mad": round(float(np.median(np.abs(arr - med))), 4),
                "distinct_count": int(vals.nunique()),
                "stall_s": float(
                    (w.end - pd.Timestamp(good["timestamp"].iloc[-1])).total_seconds()
                ),
                "changes_per_hour": round(changes / span_h, 4),
            }
        )
    return {"train": out[0], "monitor": out[1]}


def build_rows(tmp: Path) -> list[tuple[str, ...]]:
    from sklearn.metrics import roc_auc_score

    from tsdive.baselines import mad_baseline, regime_baselines, screen, screen_regime
    from tsdive.changepoints import segment_window
    from tsdive.compare import compare as compare_periods
    from tsdive.data import generate_backbone
    from tsdive.detectors.isolation import (
        prepare_rows,
        score_isolation,
        train_isolation,
    )
    from tsdive.features import extract
    from tsdive.mspc import align_windows, detect, fit_pca
    from tsdive.spc import apply_rules, individuals_limits
    from tsdive.store.quality import good_mask
    from tsdive.store.tagstore import TagStore

    bb = generate_backbone(tmp / "backbone", seed=42, n_loops=4, hours=48)
    truth = bb.truth
    store = TagStore(bb.root)
    pv_ids = sorted(
        (t for t in store.list_tags() if t.point_id.endswith("PV")),
        key=lambda t: (t.source_id, t.point_id),
    )
    rows: list[tuple[str, ...]] = []

    # ---- stage 2: features replay-stable ----
    f1 = [_window_features(store, i)["train"] for i in pv_ids]
    f1b = [_window_features(store, i)["train"] for i in pv_ids]
    stable = "yes" if f1 == f1b else "NO"
    rows.append(("2", "feature extraction replay-stable", stable, "backbone seed=42", ""))
    feat_row = extract(
        store.read_window(pv_ids[0], DAY1[0].to_pydatetime(), DAY1[1].to_pydatetime(), _contract())
    )
    rows.append(
        ("2", "feature columns per window", str(len(feat_row.to_row())), "backbone seed=42", "")
    )

    # ---- stages 3+4: screens on the level-shift loop ----
    shift = truth.iloc[0]
    fs, fe = pd.Timestamp(shift["start"]), pd.Timestamp(shift["end"])
    hist0 = pd.read_parquet(store.archive_path(pv_ids[0]))
    history0 = hist0[
        (hist0["timestamp"] >= DAY1[0]) & (hist0["timestamp"] < DAY1[1])
    ]
    monitor0 = hist0[
        (hist0["timestamp"] >= DAY2[0]) & (hist0["timestamp"] < DAY2[1])
    ]

    base3 = mad_baseline(history0)
    res3 = screen(base3, monitor0, k=3.0)
    in_fault_mask = (monitor0["timestamp"] >= fs) & (monitor0["timestamp"] <= fe)
    n_in_fault = len(monitor0[in_fault_mask])
    hit3 = sum(fs <= t <= fe for t in res3.flagged_timestamps)
    det3 = f"{hit3 / max(n_in_fault, 1) * 100:.0f}%"
    rows.append(
        ("3", "MAD screen detection @level_shift", det3, "backbone seed=42 loop0", "provisional")
    )
    clean3 = screen(base3, history0, k=3.0)
    ff3 = f"{clean3.n_flagged / max(clean3.n_screened, 1) * 100:.1f}%"
    rows.append(
        ("3", "MAD false-flag rate (clean day)", ff3, "backbone seed=42 loop0", "provisional")
    )

    mode_ident = next(t for t in store.list_tags() if t.point_id == "FIC000.MODE")
    modes0 = pd.read_parquet(store.archive_path(mode_ident))[["timestamp", "value"]]
    modes0 = modes0.rename(columns={"value": "mode"})
    j = modes0.merge(hist0[["timestamp", "value", "quality"]], on="timestamp")
    train4 = j[j["timestamp"] < DAY2[0]]
    mon4 = j[j["timestamp"] >= DAY2[0]]
    bases4 = regime_baselines(train4, train4["mode"])
    res4 = screen_regime(bases4, mon4, mon4["mode"], k=3.0)
    hit4 = sum(fs <= t <= fe for t in res4.flagged_timestamps)
    det4 = f"{hit4 / max(n_in_fault, 1) * 100:.0f}%"
    rows.append(
        ("4", "regime screen detection @level_shift", det4, "backbone seed=42 loop0", "MODE-keyed")
    )

    # ---- stage 4: segmentation for a tag with no MODE tag ----
    # Positions on a 60 s grid, so one sample is one minute. The window is
    # the whole archive: DAY2 starts exactly on the fault's first sample,
    # which no segmenter can find at the edge of what it was shown.
    def offset_samples(breaks, when) -> int:
        return round(min(abs((b - when).total_seconds()) / 60.0 for b in breaks))

    full0 = store.read_window(
        pv_ids[0], DAY1[0].to_pydatetime(), DAY2[1].to_pydatetime(), _contract()
    )
    seg0 = segment_window(full0)
    rows.append(
        (
            "4",
            "segment break offset from level_shift start (samples)",
            str(offset_samples(seg0.breakpoints, fs)),
            "backbone seed=42 loop0 48h",
            "the PV lags its own SP step",
        )
    )
    rows.append(
        (
            "4",
            "segment break offset from level_shift end (samples)",
            str(offset_samples(seg0.breakpoints, fe)),
            "backbone seed=42 loop0 48h",
            "no break there: the step is 0.3 of the window's MAD-sigma",
        )
    )
    rows.append(
        (
            "4",
            "segment breakpoints over 48 h",
            str(len(seg0.breakpoints)),
            "backbone seed=42 loop0 48h",
            "11 true change points: the SP steps every 4 h",
        )
    )
    # Day 1 is the clean half: every fault starts at day 2's first sample.
    clean0 = store.read_window(
        pv_ids[0],
        DAY1[0].to_pydatetime(),
        (DAY1[1] - pd.Timedelta(1, unit="min")).to_pydatetime(),
        _contract(),
    )
    rows.append(
        (
            "4",
            "segment breakpoints over a clean day",
            str(len(segment_window(clean0).breakpoints)),
            "backbone seed=42 loop0 day1",
            "the 5 SP steps day 1 holds; none invented",
        )
    )
    full1 = store.read_window(
        pv_ids[1], DAY1[0].to_pydatetime(), DAY2[1].to_pydatetime(), _contract()
    )
    rows.append(
        (
            "4",
            "segment breakpoints over 48 h (drift loop)",
            str(len(segment_window(full1).breakpoints)),
            "backbone seed=42 loop1 48h",
            "the 11 SP steps; a ramp is not a step and adds none",
        )
    )

    # ---- stage 4: compare, day 1 against day 2 over every PV and SP ----
    # The backbone has no OP tag; SP is the other numeric role it carries.
    compare_ids = sorted(
        (t for t in store.list_tags() if t.point_id.endswith((".PV", ".SP"))),
        key=lambda t: (t.source_id, t.point_id),
    )
    cmp = compare_periods(
        [str(store.archive_path(i)) for i in compare_ids],
        f"{DAY1[0].isoformat()}/{DAY1[1].isoformat()}",
        f"{DAY2[0].isoformat()}/{DAY2[1].isoformat()}",
    )
    tags_used = f"backbone seed=42 {len(compare_ids)} tags (4xPV, 4xSP)"
    first = cmp.tags[0]
    rows.append(
        (
            "4",
            "compare, tag ranked first",
            f"{first.tag} {first.level_shift_sigma:+.2f} sigma, spread x"
            f"{first.spread_ratio:.2f}",
            tags_used,
            "the stuck_sensor loop: the freeze holds the PV at the level it "
            "reached before its setpoint stepped down, which lifts the day's "
            "median and halves its MAD",
        )
    )
    shift_pv = next(t for t in cmp.tags if t.tag.endswith("FIC000.PV"))
    rows.append(
        (
            "4",
            "compare, level shift of the level_shift loop's PV",
            f"{shift_pv.level_shift_sigma:+.4f} sigma "
            f"(rank {cmp.tags.index(shift_pv) + 1} of {len(cmp.tags)})",
            tags_used,
            "the injected 8-unit step covers 4 h of a day whose PV cycles the "
            "three regimes 40/55/70, so the day's MAD is 14.5 and its median "
            "moves 0.01",
        )
    )
    top_pair = cmp.pairs.pairs[0]
    rows.append(
        (
            "4",
            "compare, largest absolute pair delta",
            f"{top_pair.delta:+.3f}",
            tags_used,
            f"{top_pair.left} against {top_pair.right}, "
            f"{top_pair.pearson_before:.3f} -> {top_pair.pearson_after:.3f}: the "
            "stuck PV stops following a setpoint. All four loops run one "
            "setpoint schedule, so this delta ties across all four SP tags",
        )
    )
    rows.append(
        (
            "4",
            "compare, pairs carrying a delta and no bootstrap interval",
            f"{cmp.pairs.n_no_interval} of {cmp.pairs.n_pairs}",
            tags_used,
            "every pair holding an SP: the differenced setpoint is 0 at all but "
            "5 samples a day, so a block resample that draws none of them "
            "leaves the column flat",
        )
    )
    contributor, share = cmp.joint.contributors[0]
    rows.append(
        (
            "4",
            "compare, SPE contribution of the top tag",
            f"{share:.0%} ({contributor})",
            tags_used,
            f"over {cmp.joint.spe_breaches} SPE breach rows of {cmp.joint.rows}; "
            f"day 1's components keep {cmp.joint.explained_before:.3f} of day 1's "
            f"variance and {cmp.joint.explained_after:.3f} of day 2's",
        )
    )

    # ---- stage 5: SPC rules on the drift loop ----
    drift = truth.iloc[1]
    fs5, fe5 = pd.Timestamp(drift["start"]), pd.Timestamp(drift["end"])
    hist1 = pd.read_parquet(store.archive_path(pv_ids[1]))
    h_hist = hist1[
        (hist1["timestamp"] >= DAY1[0]) & (hist1["timestamp"] < DAY1[1])
    ]
    h_mon = hist1[
        (hist1["timestamp"] >= DAY2[0]) & (hist1["timestamp"] < DAY2[1])
    ]
    base5 = mad_baseline(h_hist)
    lim5 = individuals_limits(base5.center, base5.scale)
    gm = h_mon[good_mask(h_mon)].reset_index(drop=True)
    hits5 = apply_rules(gm["timestamp"], gm["value"].astype(float), lim5)
    by_rule: dict[str, int] = {}
    inside5 = 0
    for hit in hits5:
        by_rule[hit.rule] = by_rule.get(hit.rule, 0) + 1
        if fs5 <= hit.timestamp <= fe5:
            inside5 += 1
    rows.append(
        ("5", "SPC rule hits inside drift interval", str(inside5), "backbone seed=42 loop1", "")
    )
    for rule in ("BEYOND_3SIGMA", "RUN_9_SAMESIDE", "TREND_6"):
        count = str(by_rule.get(rule, 0))
        rows.append(("5", f"rule {rule} hits", count, "backbone seed=42 loop1", ""))

    # ---- stage 6: MSPC across all PVs ----
    w_train = [
        store.read_window(i, DAY1[0].to_pydatetime(), DAY1[1].to_pydatetime(), _contract())
        for i in pv_ids
    ]
    w_mon = [
        store.read_window(i, DAY2[0].to_pydatetime(), DAY2[1].to_pydatetime(), _contract())
        for i in pv_ids
    ]
    model6 = fit_pca(align_windows(w_train, rate_s=60, min_coverage=0.9))
    det6 = detect(model6, align_windows(w_mon, rate_s=60, min_coverage=0.9))
    burst = truth.iloc[3]  # variance_burst on loop3
    fs6, fe6 = pd.Timestamp(burst["start"]), pd.Timestamp(burst["end"])
    breach_ts = det6.t2_breaches
    inside6 = sum(1 for t in breach_ts if fs6 <= t <= fe6)
    rows.append(
        (
            "6",
            "T2 breaches inside variance_burst interval",
            str(inside6),
            "backbone seed=42 4xPV",
            "empirical 99% limit",
        )
    )
    spe_inside6 = sum(1 for t in det6.spe_breaches if fs6 <= t <= fe6)
    rows.append(
        (
            "6",
            "SPE breaches inside variance_burst interval",
            str(spe_inside6),
            "backbone seed=42 4xPV",
            "variance faults surface in residuals",
        )
    )
    rows.append(
        (
            "6",
            "T2 breaches total (day 2)",
            str(len(breach_ts)),
            "backbone seed=42 4xPV",
            "includes drift/spike loops",
        )
    )

    # ---- stage 7: IsolationForest AUC over 4 h window features ----
    def slices(lo, hi):
        step = int((hi - lo).total_seconds())
        n_chunks = step // (4 * 3600)
        return [
            (
                lo + pd.Timedelta(4 * 3600 * i, unit="s"),
                lo + pd.Timedelta(4 * 3600 * (i + 1), unit="s"),
            )
            for i in range(n_chunks)
        ]

    feat_rows, labels = [], []

    def feats_for(frame: pd.DataFrame, lo, hi):
        wdf = frame[(frame["timestamp"] >= lo) & (frame["timestamp"] < hi)]
        good = wdf[good_mask(wdf)]
        vals = good["value"].astype(float)
        arr = vals.to_numpy(dtype=float)
        med = float(np.median(arr))
        changes = int((vals.diff().fillna(0.0) != 0).sum())
        span_h = (hi - lo).total_seconds() / 3600.0
        end_ts = pd.Timestamp(good["timestamp"].iloc[-1])
        return {
            "weighted_mean": round(float(vals.mean()), 4),
            "std": round(float(vals.std()), 4),
            "min": round(float(vals.min()), 4),
            "max": round(float(vals.max()), 4),
            "median": round(med, 4),
            "mad": round(float(np.median(np.abs(arr - med))), 4),
            "distinct_count": int(vals.nunique()),
            "stall_s": float((hi - end_ts).total_seconds()),
            "changes_per_hour": round(changes / span_h, 4),
        }

    for li, ident in enumerate(pv_ids):
        h = pd.read_parquet(store.archive_path(ident))
        trow = truth.iloc[li]
        ffs, ffe = pd.Timestamp(trow["start"]), pd.Timestamp(trow["end"])
        for lo, hi in slices(DAY1[0], DAY1[1]):
            feat_rows.append(feats_for(h, lo, hi))
            labels.append(0)
        for lo, hi in slices(DAY2[0], DAY2[1]):
            feat_rows.append(feats_for(h, lo, hi))
            labels.append(1 if not (hi <= ffs or lo >= ffe) else 0)

    fr = pd.DataFrame(feat_rows)
    tagged = fr.assign(tag="t", window_start=[f"{i:03d}" for i in range(len(fr))])
    tr_idx = [i for i, lab in enumerate(labels) if lab == 0]
    train7, _ = prepare_rows(tagged.iloc[tr_idx])
    model7 = train_isolation(train7)
    allrows, excluded7 = prepare_rows(tagged)
    scores = score_isolation(model7, allrows, n_excluded_incomplete=excluded7).scores.to_numpy()
    # prepare_rows sorts rows; recover each scored row's original id so
    # labels align with what was actually scored.
    orig_ids = allrows["window_start"].astype(int).to_numpy()
    y = np.array(labels)[orig_ids]
    auc = float(roc_auc_score(y, scores))
    rows.append(
        (
            "7",
            "IsolationForest ROC-AUC (fault vs normal)",
            f"{auc:.3f}",
            "backbone seed=42 48x4h windows",
            "SYNTHETIC only",
        )
    )

    return rows


def render(rows: list[tuple[str, ...]]) -> str:
    lines = [HEADER, "| stage | metric | value | dataset | caveat |", "|---|---|---|---|---|"]
    lines.extend("| " + " | ".join(r) + " |" for r in rows)
    return "\n".join(lines) + "\n"


def split_appended(text: str) -> tuple[str, str]:
    """Split a committed BENCHMARKS.md into (generated part, appended part).

    The cut is at the *first* ``## REAL`` heading, so every real-data
    section after it travels through regeneration together. Adding a
    study means appending a section; it never means touching this file.
    """
    idx = text.find(APPENDED_MARKER)
    return (text, "") if idx < 0 else (text[:idx], text[idx:])


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--update", action="store_true")
    args = parser.parse_args(argv)

    with tempfile.TemporaryDirectory() as tmp:
        rows = build_rows(Path(tmp))
    committed = BENCH_MD.read_text(encoding="utf-8") if BENCH_MD.exists() else ""
    _, appended = split_appended(committed)
    rendered = render(rows) + appended

    if args.update or not BENCH_MD.exists():
        BENCH_MD.write_text(rendered, encoding="utf-8", newline="\n")
        print(f"wrote {BENCH_MD}")
        return 0
    if committed == rendered:
        print("OK   BENCHMARKS.md byte-identical")
        return 0
    print("FAIL BENCHMARKS.md differs; rerun with --update")
    return 1


if __name__ == "__main__":
    sys.exit(main())
